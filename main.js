const nodes = document.querySelectorAll("[data-i18n],[data-i18n-html]");
const EN = new Map();
nodes.forEach(n => EN.set(n, n.innerHTML));

let counts = null;

// Affiche les compteurs ; sans aucune donnée (API en panne et rien en mémoire), on les cache
function renderCounts() {
  const box = document.getElementById("counter");
  box.hidden = !counts || counts.total === 0;
  if (!counts) return;
  const en = document.documentElement.lang !== "fr";
  const fmt = n => n.toLocaleString(en ? "en-US" : "fr-FR");
  document.getElementById("total").textContent = fmt(counts.total);
  document.querySelectorAll("[data-count]").forEach(el => {
    const p = counts.plugins[el.dataset.count];
    if (!p) { el.textContent = ""; return; }
    if (p.total === 0) { el.textContent = en ? "Be the first to download it!" : "Sois le premier à le télécharger !"; return; }
    el.innerHTML = `<b>${fmt(p.total)}</b> ${en ? (p.total > 1 ? "downloads" : "download") : (p.total > 1 ? "téléchargements" : "téléchargement")} · Mac ${fmt(p.mac)} · Windows ${fmt(p.win)}`;
  });
}

function setLang(lang) {
  nodes.forEach(n => {
    const key = n.dataset.i18n || n.dataset.i18nHtml;
    n.innerHTML = lang === "fr" && FR[key] ? FR[key] : EN.get(n);
  });
  document.querySelectorAll(".sz").forEach(n => { n.textContent = n.dataset[lang]; });
  document.documentElement.lang = lang;
  document.title = lang === "fr" ? "Plugins gratuits de Benjamin Franklin : Plug de fou, SlowMo, Boom" : "Free plugins by Benjamin Franklin: Plug de fou, SlowMo, Boom";
  document.querySelectorAll(".lang").forEach(b => b.classList.toggle("on", b.dataset.lang === lang));
  renderCounts();
}

